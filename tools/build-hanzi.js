/* Rebuild the offline deck: node tools/build-hanzi.js. Sources/licenses in tools/data. */
'use strict';
var fs = require('fs');
var path = require('path');
var root = path.join(__dirname, '..');
var readings = {};
fs.readFileSync(path.join(__dirname, 'data/pinyin.txt'), 'utf8').split(/\r?\n/).forEach(function (line) {
  var m = /^U\+([0-9A-F]+): ([^#]+)/.exec(line);
  if (m) readings[String.fromCodePoint(parseInt(m[1], 16))] = m[2].trim().split(',');
});
var levels = [], current = null, seen = {};
fs.readFileSync(path.join(__dirname, 'data/hsk30-characters.txt'), 'utf8').split(/\r?\n/).forEach(function (line) {
  if (/^[一二三四五六七].*级汉字表$/.test(line)) { current = []; levels.push(current); return; }
  if (/手写字表/.test(line)) current = null;
  var m = /^\d+\s+(\S+)\s*$/.exec(line);
  if (!m || !current) return;
  var char = m[1];
  if (Array.from(char).length !== 1 || !readings[char] || seen[char]) throw new Error('Invalid/duplicate character: ' + char);
  seen[char] = true;
  current.push([char, readings[char]]);
});
if (levels.length !== 7 || levels.some(function (l, i) { return l.length !== (i === 6 ? 1200 : 300); })) {
  throw new Error('Unexpected HSK level counts: ' + levels.map(function (l) { return l.length; }));
}
fs.writeFileSync(path.join(root, 'js/hanzi-characters.js'),
  '/* Generated by tools/build-hanzi.js; HSK 3.0 (Pleco, MIT), pinyin-data (MIT). */\n' +
  '(function (global) { global.HSK_CHARACTERS = ' + JSON.stringify(levels) + '; })(this);\n');
console.log('Generated ' + Object.keys(seen).length + ' HSK characters.');
